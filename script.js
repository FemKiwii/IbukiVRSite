// 1. Initialize Content
function initProfile() {
    document.getElementById('profile-name').textContent = userConfig.name;
    document.getElementById('profile-bio').textContent = userConfig.bio;
    document.getElementById('profile-img').src = userConfig.avatar;

    const linksWrapper = document.getElementById('links-wrapper');
    
    // Loop through categories
    userConfig.categories.forEach(category => {
        // Create Category Section
        const section = document.createElement('div');
        section.className = 'category-section';

        // Create Header Container
        const header = document.createElement('div'); 
        header.className = 'category-header';

        // Create a Span for the Text
        const textSpan = document.createElement('span');
        textSpan.textContent = category.title;

        // Append the text span INSIDE the header
        header.appendChild(textSpan);

        // Append the header to the section
        section.appendChild(header);

        // Create Grid
        const grid = document.createElement('div');
        grid.className = 'links-grid';

        // Generate Link Cards
        category.links.forEach(link => {
            const a = document.createElement('a');
            a.className = 'link-card';
            a.href = link.url;
            a.target = '_blank';
            a.rel = 'noopener noreferrer';

            // Get SVG path or fallback to generic website icon
            const iconPath = icons[link.icon] || icons['website'];
            
            // Log warning if icon is missing
            if (!icons[link.icon]) {
                console.warn(`Icon "${link.icon}" not found. Using default.`);
            }

            a.innerHTML = `
                <svg class="link-icon" viewBox="0 0 24 24" xmlns="http://www.w3.org/2000/svg">
                    ${iconPath}
                </svg>
                <span class="link-text">${link.title}</span>
                <svg class="link-arrow" viewBox="0 0 24 24" xmlns="http://www.w3.org/2000/svg">
                    <path d="M12 4l-1.41 1.41L16.17 11H4v2h12.17l-5.58 5.59L12 20l8-8z"/>
                </svg>
            `;
            grid.appendChild(a);
        });

        section.appendChild(grid);
        linksWrapper.appendChild(section);
    });
}

// 2. Theme Handling (Dark Mode Default)
function initTheme() {
    const toggleBtn = document.getElementById('theme-btn');
    const html = document.documentElement;
    
    // Check local storage first
    const savedTheme = localStorage.getItem('theme');

    // If user has previously saved a preference, use it. 
    // Otherwise, default to 'dark'.
    if (savedTheme) {
        html.setAttribute('data-theme', savedTheme);
    } else {
        html.setAttribute('data-theme', 'dark');
    }

    toggleBtn.addEventListener('click', () => {
        const currentTheme = html.getAttribute('data-theme');
        const newTheme = currentTheme === 'dark' ? 'light' : 'dark';
        
        html.setAttribute('data-theme', newTheme);
        localStorage.setItem('theme', newTheme);
    });
}

// 3. Background Animation (Canvas Particles)
function initAnimation() {
    const canvas = document.getElementById('bg-canvas');
    const ctx = canvas.getContext('2d');
    let particles = [];
    
    function resize() {
        canvas.width = window.innerWidth;
        canvas.height = window.innerHeight;
    }
    window.addEventListener('resize', resize);
    resize();

    class Particle {
        constructor() {
            this.x = Math.random() * canvas.width;
            this.y = Math.random() * canvas.height;
            this.vx = (Math.random() - 0.5) * 0.5;
            this.vy = (Math.random() - 0.5) * 0.5;
            this.size = Math.random() * 2 + 1;
        }

        update() {
            this.x += this.vx;
            this.y += this.vy;

            // Bounce off edges
            if (this.x < 0 || this.x > canvas.width) this.vx *= -1;
            if (this.y < 0 || this.y > canvas.height) this.vy *= -1;
        }

        draw() {
            // Get current CSS variable for text color to match particles
            const style = getComputedStyle(document.body);
            ctx.fillStyle = style.getPropertyValue('--text-secondary').trim();
            ctx.globalAlpha = 0.3;
            ctx.beginPath();
            ctx.arc(this.x, this.y, this.size, 0, Math.PI * 2);
            ctx.fill();
        }
    }

    // Create particles
    for (let i = 0; i < 50; i++) {
        particles.push(new Particle());
    }

    function animate() {
        ctx.clearRect(0, 0, canvas.width, canvas.height);
        
        particles.forEach((p, index) => {
            p.update();
            p.draw();
            
            // Draw connections
            for (let j = index + 1; j < particles.length; j++) {
                const p2 = particles[j];
                const dx = p.x - p2.x;
                const dy = p.y - p2.y;
                const dist = Math.sqrt(dx * dx + dy * dy);

                if (dist < 150) {
                    const style = getComputedStyle(document.body);
                    ctx.strokeStyle = style.getPropertyValue('--text-secondary').trim();
                    ctx.globalAlpha = 0.1 * (1 - dist / 150);
                    ctx.lineWidth = 1;
                    ctx.beginPath();
                    ctx.moveTo(p.x, p.y);
                    ctx.lineTo(p2.x, p2.y);
                    ctx.stroke();
                }
            }
        });
        
        requestAnimationFrame(animate);
    }
    animate();
}

// 4. Share Functionality
function initShare() {
    const shareBtn = document.getElementById('share-btn');
    const profileImgWrapper = document.querySelector('.profile-img-wrapper');
    const toast = document.getElementById('toast');

    // Helper to show toast
    function showToast(message) {
        toast.textContent = message;
        toast.classList.remove('hidden');
        setTimeout(() => {
            toast.classList.add('hidden');
        }, 3000);
    }

    // Handle Share Button Click
    shareBtn.addEventListener('click', async () => {
        const shareData = {
            title: userConfig.name,
            text: userConfig.bio,
            url: window.location.href
        };

        if (navigator.share) {
            try {
                await navigator.share(shareData);
            } catch (err) {
                console.error('Error sharing:', err);
            }
        } else {
            // Fallback: Copy to clipboard
            navigator.clipboard.writeText(window.location.href).then(() => {
                showToast('Link copied to clipboard!');
            });
        }
    });

    // Handle Profile Image Click (Copy Link)
    profileImgWrapper.addEventListener('click', () => {
        navigator.clipboard.writeText(window.location.href).then(() => {
            showToast('Profile link copied!');
        });
    });
}

// 5. Modal Functionality (Legal & QR)
function initModals() {
    const modalBtns = document.querySelectorAll('.legal-btn');
    const qrBtn = document.getElementById('qr-btn'); // Select the new QR button
    const closeBtns = document.querySelectorAll('.close-modal');
    const modals = document.querySelectorAll('.modal');

    // Open Legal Modals
    modalBtns.forEach(btn => {
        btn.addEventListener('click', () => {
            const modalId = btn.getAttribute('data-modal');
            document.getElementById(modalId).classList.add('active');
        });
    });

    // Open QR Modal
    if(qrBtn) {
        qrBtn.addEventListener('click', () => {
            const qrModal = document.getElementById('qr-modal');
            qrModal.classList.add('active');
        });
    }

    // Close Modal (X button)
    closeBtns.forEach(btn => {
        btn.addEventListener('click', () => {
            btn.closest('.modal').classList.remove('active');
        });
    });

    // Close Modal (Click outside)
    window.addEventListener('click', (e) => {
        if (e.target.classList.contains('modal')) {
            e.target.classList.remove('active');
        }
    });

    // Initialize QR Code Image Source
    const qrImage = document.getElementById('qr-image');
    if (qrImage) {
        // Using a public API for QR code generation
        qrImage.src = `https://api.qrserver.com/v1/create-qr-code/?size=200x200&data=${encodeURIComponent(window.location.href)}`;
    }
}

